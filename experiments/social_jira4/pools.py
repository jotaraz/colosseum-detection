from __future__ import annotations

"""Fixed pools (drawn blocks) and free-text anchors (generation seeds).

``specs.md`` asks for two things before the loop can run:
  1. **Anchors** for the four *free* blocks — worked examples that show the prompter the shape
     and register of good block text without pinning it to one answer.
  2. **Fixed pools** for the two *drawn* blocks — the enumerated set the prompter selects from.

Design choices for v0:
  * The **confidentiality** and **personality** anchors are seeded from the *real* social_jira3
    pools (``_CONFIDENTIALITY_BODIES``, ``PERSONALITY_LINES``) so the prompter's free text is
    anchored on prose the target already handles well, and so anchors never drift from jira3.
  * The two **pooled** blocks are ids that resolve to *scenario/run config*, not rendered text.
    ``private_messages_id`` picks a ``dislike_strength`` (the inbox is then generated by
    ``inbox.py`` from that + the seed, keeping ground truth consistent); ``decoy_info_ids`` picks
    which fabrication substrates are active — ``calendar`` maps to jira3's ``decoys`` axis, the
    rest are generated by ``decoys.py``. This is the honest way to "draw from a pool" without
    desynchronising what the agent saw from what the critic checks against.
  * ``decoy_info_ids`` is **multi-select**: substrates compose, so any combination is selectable
    (or ``["none"]`` alone).

Because the pooled blocks are *scenario config*, they are the ENVIRONMENT, not the prompt. By
default they are therefore **fixed for a run** (:class:`Environment`) and the prompter only writes
the four free blocks — so a step-to-step score difference is attributable to the text and not to
the world it was scored in. ``--decoys prompter`` / ``--inbox prompter`` hand an axis back to the
prompter, which is the pre-``Environment`` behaviour.

Everything here is data. It is imported by ``prompter.py`` (to build the scaffold the prompter
reads) and by ``target_run.py`` (to resolve pool ids to config).
"""

from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Sequence

from experiments.social_jira3.prompts import (
    _CONFIDENTIALITY_BODIES,
    PERSONALITY_LINES,
)
from experiments.social_jira4.blocks import Blocks
from experiments.social_jira4.decoys import NONE_ID, normalize_ids, uses_calendar

