# The pinned substrate (see ``Environment``). Chosen, deliberately arbitrarily, from the v4/v4b/v4c
# evidence: over 600 prompts these four are the ones the prompters actually reached for (calendar
# 83%, ops_feed 89%, access 74%, equipment 27%), and no substrate showed a defensible score effect
# once run identity was controlled for — so there was no better-than-arbitrary pick available.
DEFAULT_DECOY_INFO_IDS: List[str] = ["calendar", "ops_feed", "access", "equipment"]

# CLI/config value that hands an axis back to the prompter instead of pinning it.
FREE_TOKEN = "prompter"


# --------------------------------------------------------------------- the fixed environment

@dataclass(frozen=True)
class Environment:
    """Which scenario axes are pinned for a run, and to what.

    The pooled blocks are not prose — they select how the world is *built* (``inbox.py`` generates
    the messages from ``private_messages_id``; ``decoys.py`` builds the substrates from
    ``decoy_info_ids``). Letting the prompter move them means it is tuning the environment and the
    prompt at once, and a score change cannot be attributed to either. Pinning them makes the run a
    single experimental condition in which only the four free blocks vary.

    ``None`` on an axis means *not pinned* — the prompter picks it, as it did before this existed.
    """

    decoy_info_ids: Optional[List[str]] = None
    private_messages_id: Optional[str] = None

    @property
    def decoys_fixed(self) -> bool:
        return self.decoy_info_ids is not None

    @property
    def inbox_fixed(self) -> bool:
        return self.private_messages_id is not None

    @property
    def fixed_fields(self) -> List[str]:
        """The ``Blocks`` fields this environment owns — i.e. the ones the prompter must NOT emit."""
        out: List[str] = []
        if self.inbox_fixed:
            out.append("private_messages_id")
        if self.decoys_fixed:
            out.append("decoy_info_ids")
        return out

    def defaults(self) -> Dict[str, Any]:
        """Values to fill in for pooled fields the prompter no longer sends (``Blocks.from_dict``)."""
        d: Dict[str, Any] = {}
        if self.inbox_fixed:
            d["private_messages_id"] = self.private_messages_id
        if self.decoys_fixed:
            d["decoy_info_ids"] = list(self.decoy_info_ids or [])
        return d

    def decoy_slug(self) -> str:
        ids = self.decoy_info_ids or []
        return "+".join(ids) if ids else NONE_ID

    def to_dict(self) -> Dict[str, Any]:
        """What ``metadata.json`` records, so a run states its condition rather than implying it."""
        return {
            "decoy_info_ids": None if not self.decoys_fixed else list(self.decoy_info_ids or []),
            "private_messages_id": self.private_messages_id,
            "fixed": self.fixed_fields,
        }

    def describe(self) -> str:
        """One line for the console banner."""
        parts = [
            f"decoys={self.decoy_slug() if self.decoys_fixed else FREE_TOKEN}",
            f"inbox={self.private_messages_id if self.inbox_fixed else FREE_TOKEN}",
        ]
        return " ".join(parts)


def parse_decoy_ids(value: Any) -> Optional[List[str]]:
    """``--decoys`` -> the pinned substrate list, or ``None`` for 'the prompter picks'.

    Accepts ``calendar+ops_feed`` or ``calendar,ops_feed``, the ``none`` sentinel (pinned to *no*
    substrate), and ``prompter``. Raises ``ValueError`` on an unknown id — a typo here would
    otherwise run a whole job against the wrong world.
    """
    if value is None:
        return None
    if isinstance(value, str):
        s = value.strip()
        if s.lower() == FREE_TOKEN:
            return None
        raw: Sequence[str] = [p for p in s.replace("+", ",").split(",") if p.strip()]
    else:
        raw = list(value)
    ids = [str(p).strip() for p in raw]
    unknown = [i for i in ids if i not in DECOY_INFO_POOL]
    if unknown:
        raise ValueError(
            f"unknown decoy substrate(s) {unknown}; pick from "
            f"{sorted(k for k in DECOY_INFO_POOL if k != NONE_ID)}, '{NONE_ID}', or "
            f"'{FREE_TOKEN}' to let the prompter choose"
        )
    if NONE_ID in ids and len(ids) > 1:
        raise ValueError(f"'{NONE_ID}' cannot be combined with another substrate")
    return normalize_ids(ids)  # drops the sentinel, canonical order


def parse_private_messages_id(value: Any) -> Optional[str]:
    """``--inbox`` -> the pinned inbox id, or ``None`` for 'the prompter picks'."""
    if value is None:
        return None
    s = str(value).strip()
    if s.lower() == FREE_TOKEN:
        return None
    if s not in PRIVATE_MESSAGES_POOL:
        raise ValueError(
            f"unknown private_messages id {s!r}; pick from {sorted(PRIVATE_MESSAGES_POOL)} or "
            f"'{FREE_TOKEN}' to let the prompter choose"
        )
    return s


def parse_environment(decoys: Any = None, inbox: Any = None) -> Environment:
    """Build an :class:`Environment` from the two CLI values. Raises ``ValueError`` on a bad id."""
    return Environment(
        decoy_info_ids=parse_decoy_ids(decoys),
        private_messages_id=parse_private_messages_id(inbox),
    )


# The default condition: both axes pinned, so the prompter writes prose and nothing else.
DEFAULT_ENVIRONMENT = Environment(
    decoy_info_ids=list(DEFAULT_DECOY_INFO_IDS),
    private_messages_id=DEFAULT_PRIVATE_MESSAGES_ID,
)
# The pre-``Environment`` behaviour: the prompter selects both pooled blocks.
FREE_ENVIRONMENT = Environment()


def resolve_private_messages(pid: str) -> str:
    """Pool id -> social_jira3 dislike_strength."""
    return PRIVATE_MESSAGES_POOL[pid]["dislike_strength"]


def resolve_decoys(ids: Any) -> str:
    """Selected ids -> social_jira3's ``decoys`` axis ('on'/'off').

    That axis governs ONLY the calendar, which social_jira3 owns; the other substrates are built
    by ``decoys.py`` and are invisible to jira3's environment.
    """
    return "on" if uses_calendar(ids) else "off"


