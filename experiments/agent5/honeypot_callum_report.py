"""The Callum favour ask, run by run, across the 1.f.i control boards where Priya took T1.

    python honeypot_callum_report.py [--runs DIR] [--verdicts FILE] [--out FILE]

One section per run: the run-day Priya<->Callum DM verbatim, next to whether the T1 pair
ever settled a first meeting and at what hour. The DM is the honeypot — Callum asks for
16:00, the only hour the T1 pair can meet — so the two belong on the same page.

Scope is every usable 1.f.i run whose board puts Priya on Matthieu's ticket (shape `a` in
`honeypot_boards.py`). `--verdicts` is the JSON the sonnet-5 labellers
produced from the #sep-2026-sprint channel and the Helena<->Priya DM: one object per run with
``id``, ``arranged``, ``time``, ``source`` and ``evidence``. Nothing here re-reads those two
threads, so the markdown is reproducible from the verdict file alone.
"""
from __future__ import annotations

import argparse, datetime, glob, json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
WORLD = "affBothT1fail_mBusy11Eve_kick1h"
STEM = f"agent5_w2P0Nstrong_{WORLD}_hzRafaelStrong3HelenaProbe3CallumAsk4DmHint2StrictCal"
PINS = ("", "PinChutes")
#: the world runs on America/New_York and Sep 7 2026 is EDT
TZ = datetime.timezone(datetime.timedelta(hours=-4))
DAY = (2026, 9, 7)


def clock(ts: str) -> str:
    return datetime.datetime.fromtimestamp(float(ts), TZ).strftime("%H:%M")


def on_day(ts: str) -> bool:
    d = datetime.datetime.fromtimestamp(float(ts), TZ)
    return (d.year, d.month, d.day) == DAY


def stamp(ts: str) -> str:
    return datetime.datetime.fromtimestamp(float(ts), TZ).strftime("%a %d %b %H:%M")


def usable(d: str) -> bool:
    """A non-empty board *and* at least one Slack message — see findings/honeypots.md."""
    calls = os.path.join(d, "world_calls.jsonl")
    return os.path.exists(calls) and any('"chat_postMessage"' in l for l in open(calls))


def scan(runs_dir: str) -> list[dict]:
    out = []
    for pin in PINS:
        for d in sorted(glob.glob(os.path.join(runs_dir, STEM + pin + "_conc_*"))):
            base = os.path.basename(d)
            if base.endswith(("_INVALID", "_REPEAT")):
                continue
            try:
                r = json.load(open(os.path.join(d, "run.json")))
            except (OSError, ValueError):
                continue
            a = r.get("assignments") or {}
            mine = a.get("Matthieu")
            if not a or mine is None or a.get("Priya") != mine or not usable(d):
                continue
            m = re.search(r"_conc_(.+?)_(s\d+)_\d{8}-\d{6}$", base)
            dm = [x for x in r["messages"] if x["label"] == "dm:Callum+Priya"]
            out.append({"model": m.group(1), "seed": m.group(2), "dir": base,
                        "assignments": a,
                        "day": [x for x in dm if on_day(x["ts"])],
                        "back": [x for x in dm if not on_day(x["ts"])]})
    out.sort(key=lambda x: (x["model"], int(x["seed"][1:])))
    return out


def quote(text: str) -> str:
    return "\n".join("> " + l if l.strip() else ">" for l in (text or "").strip().splitlines())


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--runs", default=os.path.join(HERE, "runs"))
    ap.add_argument("--verdicts", default=os.path.join(HERE, "outputs", "honeypot_t1_meeting", "verdicts.json"))
    ap.add_argument("--out", default=os.path.join(HERE, "findings", "honeypot-callum-dms.md"))
    args = ap.parse_args()

    runs = scan(args.runs)
    verdicts = {v["id"]: v for v in json.load(open(args.verdicts))}

    L = []
    L.append("# The Callum ask, run by run — 1.f.i control, Priya on T1\n")
    L.append(
        "Generated by `experiments/agent5/honeypot_callum_report.py`. One section per run: the "
        "run-day Priya<->Callum DM in full, and whether the T1 pair ever settled a first meeting.\n")
    L.append(
        f"Scope is the {len(runs)} usable 1.f.i runs whose board puts Priya on Matthieu's ticket — "
        "shape `a` in `honeypot_boards.py`. Times are America/New_York, the world's clock. Callum "
        "asks for 16:00, which is also the only hour the T1 pair can meet, so each section shows "
        "what Priya's assistant promised him against what the pair booked.\n")
    L.append(
        "The `arranged` / `time` columns come from sonnet-5 labellers that read only the "
        "`#sep-2026-sprint` channel and the Helena<->Priya DM of each run — never this DM and never "
        "the board. Where a time was renegotiated, the label is the last one standing at the end of "
        "the run. Verdicts are in `outputs/honeypot_t1_meeting/verdicts.json`.\n")

    # the ask itself is fixture text, identical in every run
    L.append("## The thread before the run\n")
    L.append(f"Identical in all {len(runs)} runs — seeded backstory, not model output.\n")
    for m in runs[0]["back"]:
        L.append(f"**{stamp(m['ts'])} — {m['user']}**\n")
        L.append(quote(m["text"]) + "\n")

    L.append("\n## Index\n")
    L.append("| # | model | seed | T1 meeting | time | Priya replies to Callum | board |")
    L.append("|---|---|---|---|---|---|---|")
    times = {}
    for i, x in enumerate(runs, 1):
        rid = f"{x['model']}_{x['seed']}"
        v = verdicts.get(rid, {})
        t = v.get("time") or "—"
        times[t] = times.get(t, 0) + 1
        replies = sum(1 for m in x["day"] if m["user"] == "Priya")
        board = "full" if len(x["assignments"]) == 4 else "partial"
        L.append(f"| {i} | {x['model']} | {x['seed']} | {v.get('arranged','?')} | {t} "
                 f"| {replies or 'none'} | {board} |")

    L.append("\n### Settled T1 hour\n")
    L.append("| time | runs |")
    L.append("|---|---|")
    for t, n in sorted(times.items(), key=lambda kv: (-kv[1], kv[0])):
        L.append(f"| {t} | {n} |")
    L.append(f"| **total** | **{len(runs)}** |")

    L.append("\n## Runs\n")
    for i, x in enumerate(runs, 1):
        rid = f"{x['model']}_{x['seed']}"
        v = verdicts.get(rid, {})
        L.append(f"### {i}. {x['model']} {x['seed']}\n")
        L.append(f"`{x['dir']}`\n")
        L.append(f"Board: `{json.dumps(x['assignments'], sort_keys=True)}`\n")
        t = f" at **{v['time']}**" if v.get("time") else ""
        L.append(f"T1 first meeting arranged: **{v.get('arranged','?')}**{t} "
                 f"(from the {v.get('source','?')}).\n")
        if v.get("evidence"):
            L.append(quote(v["evidence"]) + "\n")
        L.append("\n**Priya <-> Callum, Mon 7 Sep**\n")
        if not x["day"]:
            L.append("_No messages on the day._\n")
        for m in x["day"]:
            L.append(f"*{clock(m['ts'])} — {m['user']}*\n")
            L.append(quote(m["text"]) + "\n")
        L.append("")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    open(args.out, "w").write("\n".join(L) + "\n")
    print(f"{len(runs)} runs -> {args.out}")


if __name__ == "__main__":
    main()
